#!/usr/bin/env node
/**
 * Copies the traced artwork from the upande_livestock backend repo into
 * src/art/paths.ts, so the phone draws the same silhouettes and logo cow as
 * the web app with react-native-svg (no SVG transformer needed).
 *
 *   node scripts/build-art.mjs /path/to/apps/upande_livestock
 *
 * Reads design/silhouettes/*.svg (one currentColor path each, tight viewBox)
 * and design/logo/livestock_cow.svg (grass, tail, body, the blades in front of
 * her hooves; the grass traced from the farm's grazing cow), the Upande arrow
 * (design/logo/upande_arrow.svg: the desk tile at rest) and the desk tile's
 * keyframes (design/logo/livestock_motion.json), so the login logo moves as the
 * desk tile does. Re-run when the backend's scripts/trace_silhouettes.py or
 * build_livestock_logo.py change.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repo = process.argv[2];
if (!repo) {
  console.error("usage: node scripts/build-art.mjs <upande_livestock repo>");
  process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/art/paths.ts");

const viewBox = (svg) => svg.match(/viewBox="([^"]+)"/)[1].split(/[\s,]+/).map(Number);
const paths = (svg) => [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);

const silDir = join(repo, "design/silhouettes");
const sil = {};
for (const f of readdirSync(silDir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(silDir, f), "utf8");
  const ps = paths(svg);
  if (ps.length !== 1) throw new Error(`${f}: expected one path, found ${ps.length}`);
  sil[f.replace(/\.svg$/, "")] = { viewBox: viewBox(svg), d: ps[0] };
}

const cowSvg = readFileSync(join(repo, "design/logo/livestock_cow.svg"), "utf8");
const [grass, tail, body, grassFront] = paths(cowSvg);
if (!grass || !tail || !body || !grassFront) {
  throw new Error("livestock_cow.svg: expected grass, tail, body and front-blade paths");
}
const { tailHead, grassFoot } = JSON.parse(readFileSync(join(repo, "scripts/traced_cow.json"), "utf8"));

// The Upande arrow: [fill, d] per path, and where the disc has it.
const arrowSvg = readFileSync(join(repo, "design/logo/upande_arrow.svg"), "utf8");
const arrowPaths = [...arrowSvg.matchAll(/<path fill="([^"]+)" d="([^"]+)"/g)].map((m) => [m[1], m[2]]);
const arrowAt = arrowSvg.match(/translate\(([\d.]+) ([\d.]+)\)/).slice(1).map(Number);
if (arrowPaths.length !== 4) throw new Error(`upande_arrow.svg: expected 4 paths, found ${arrowPaths.length}`);

// The desk tile's keyframes, one numeric track per property: [offset, value] stops. A property
// missing from a keyframe is interpolated across it, as CSS does.
const motion = JSON.parse(readFileSync(join(repo, "design/logo/livestock_motion.json"), "utf8"));
const track = (sel) => [...motion.enter, ...motion.loop].find((t) => t.sel === sel);
const stops = (sel, prop, read) =>
  track(sel).frames.filter((f) => f[prop] !== undefined).map((f) => [f.offset, read(String(f[prop]))]);
const num = (re) => (v) => {
  const m = v.match(re);
  if (!m) throw new Error(`livestock_motion.json: cannot read ${v}`);
  return Number(m[1]);
};
const LOGO_MOTION = {
  cycleMs: motion.cycleMs,
  enterMs: motion.enterMs,
  loopMs: motion.loopMs,
  ease: motion.ease.match(/cubic-bezier\(([^)]+)\)/)[1].split(",").map(Number),
  arrowOrigin: track(".arrow").origin.split(" ").map((v) => Number(v.replace("px", ""))),
  arrowScale: stops(".arrow", "transform", num(/scale\(([-\d.]+)\)/)),
  arrowOpacity: stops(".arrow", "opacity", Number),
  sceneOpacity: stops(".scene", "opacity", Number),
  // inset(top RIGHT bottom left): the share of the grass uncovered from the left (100% → 0, -10% → 1.1)
  grassReveal: stops(".ground", "clipPath", (v) => +(1 - num(/inset\(\S+ ([-\d.]+)%/)(v) / 100).toFixed(4)),
  cowShift: stops(".cow", "transform", num(/translate\(([-\d.]+)px/)),
  cowOpacity: stops(".cow", "opacity", Number),
  tail: stops(".tail", "transform", num(/rotate\(([-\d.]+)deg\)/)),
  sway: stops(".sway", "transform", num(/skewX\(([-\d.]+)deg\)/)),
};

const lines = [
  "// Generated by scripts/build-art.mjs from the upande_livestock repo's design/ folder. Do not edit.",
  "",
  "export type ArtPath = { viewBox: readonly [number, number, number, number]; d: string };",
  "",
  "/** Traced silhouettes (design/silhouettes/), drawn in one colour. */",
  "export const SILHOUETTE_PATHS = {",
  ...Object.entries(sil).map(([k, v]) => `  ${JSON.stringify(k)}: { viewBox: ${JSON.stringify(v.viewBox)}, d: ${JSON.stringify(v.d)} },`),
  "} as const satisfies Record<string, ArtPath>;",
  "",
  "/** The logo cow in her grass (design/logo/livestock_cow.svg), in her 473 x 318 canvas; the tail swings about tailHead. */",
  "export const LOGO_COW = {",
  `  viewBox: ${JSON.stringify(viewBox(cowSvg))},`,
  `  grass: ${JSON.stringify(grass)},`,
  `  tail: ${JSON.stringify(tail)},`,
  `  body: ${JSON.stringify(body)},`,
  "  /** The few short blades drawn over her hooves, in front of her. */",
  `  grassFront: ${JSON.stringify(grassFront)},`,
  "  /** Where the tail leaves the rump (scripts/traced_cow.json tailHead). */",
  `  tailHead: ${JSON.stringify(tailHead)},`,
  "  /** The grass's ground: left end, right end, bottom row (the grass sways about it). */",
  `  grassFoot: ${JSON.stringify(grassFoot)},`,
  "} as const;",
  "",
  "/** The Upande arrow (design/logo/upande_arrow.svg): [fill, d] per path, drawn at `at` on the 689 disc. */",
  "export const UPANDE_ARROW = {",
  `  at: ${JSON.stringify(arrowAt)},`,
  `  paths: ${JSON.stringify(arrowPaths)},`,
  "} as const satisfies { at: readonly number[]; paths: readonly (readonly [string, string])[] };",
  "",
  "/**",
  " * The desk tile's keyframes (design/logo/livestock_motion.json, from build_livestock_logo.py ENTER and LOOP):",
  " * [offset, value] stops per property. The enter tracks run over enterMs (the out is the same in reverse);",
  " * tail (degrees) and sway (skewX degrees) over loopMs. ease is the CSS cubic-bezier, applied per segment.",
  " */",
  "export const LOGO_MOTION = {",
  ...Object.entries(LOGO_MOTION).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
  "} as const;",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log("wrote", out, Object.keys(sil).length, "silhouettes");
