#!/usr/bin/env node
/**
 * Copies the traced artwork from the upande_livestock backend repo into
 * src/art/paths.ts, so the phone draws the same silhouettes and logo cow as
 * the web app with react-native-svg (no SVG transformer needed).
 *
 *   node scripts/build-art.mjs /path/to/apps/upande_livestock
 *
 * Reads design/silhouettes/*.svg (one currentColor path each, tight viewBox)
 * and design/logo/livestock_cow.svg (grass, tail, body). Re-run when the
 * backend's scripts/trace_silhouettes.py or build_livestock_logo.py change.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repo = process.argv[2];
if (!repo) {
  console.error("usage: node scripts/build-art.mjs <upande_livestock repo>");
  process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/art/paths.ts");

const viewBox = (svg) => svg.match(/viewBox="([^"]+)"/)[1].split(/[\s,]+/).map(Number);
const paths = (svg) => [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);

const silDir = join(repo, "design/silhouettes");
const sil = {};
for (const f of readdirSync(silDir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(silDir, f), "utf8");
  const ps = paths(svg);
  if (ps.length !== 1) throw new Error(`${f}: expected one path, found ${ps.length}`);
  sil[f.replace(/\.svg$/, "")] = { viewBox: viewBox(svg), d: ps[0] };
}

const cowSvg = readFileSync(join(repo, "design/logo/livestock_cow.svg"), "utf8");
const [grass, tail, body] = paths(cowSvg);
if (!grass || !tail || !body) throw new Error("livestock_cow.svg: expected grass, tail and body paths");
const { tailHead } = JSON.parse(readFileSync(join(repo, "scripts/traced_cow.json"), "utf8"));

const lines = [
  "// Generated by scripts/build-art.mjs from the upande_livestock repo's design/ folder. Do not edit.",
  "",
  "export type ArtPath = { viewBox: readonly [number, number, number, number]; d: string };",
  "",
  "/** Traced silhouettes (design/silhouettes/), drawn in one colour. */",
  "export const SILHOUETTE_PATHS = {",
  ...Object.entries(sil).map(([k, v]) => `  ${JSON.stringify(k)}: { viewBox: ${JSON.stringify(v.viewBox)}, d: ${JSON.stringify(v.d)} },`),
  "} as const satisfies Record<string, ArtPath>;",
  "",
  "/** The logo cow on her grass (design/logo/livestock_cow.svg); the tail swings about TAIL_HEAD. */",
  "export const LOGO_COW = {",
  `  viewBox: ${JSON.stringify(viewBox(cowSvg))},`,
  `  grass: ${JSON.stringify(grass)},`,
  `  tail: ${JSON.stringify(tail)},`,
  `  body: ${JSON.stringify(body)},`,
  "  /** Where the tail leaves the rump (scripts/traced_cow.json tailHead). */",
  `  tailHead: ${JSON.stringify(tailHead)},`,
  "} as const;",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log("wrote", out, Object.keys(sil).length, "silhouettes");
